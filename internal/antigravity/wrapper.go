package antigravity

import (
	"errors"
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"strings"
)

// WrapperDir is the generated "Antigravity Proxy.app" bundle.
func WrapperDir(appDir string) string {
	return filepath.Join(appDir, DefaultAppName+".app")
}

func WrapperExe(appDir string) string {
	return filepath.Join(WrapperDir(appDir), WrapperRel)
}

// WrapperScript renders the bundle's launcher. It sets the Go backend's proxy
// environment and passes the Chromium proxy switches to the real binary, so a
// Dock/Spotlight launch gets full coverage without touching global settings.
func WrapperScript(u *url.URL, mainBinary string) string {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString("# Generated by proxy-antigravity. Re-run `proxy-antigravity install` to update.\n")
	b.WriteString("set -eu\n")
	b.WriteString("export HTTPS_PROXY=" + ShellQuote(u.String()) + "\n")
	b.WriteString("export HTTP_PROXY=\"$HTTPS_PROXY\"\n")
	b.WriteString("export ALL_PROXY=\"$HTTPS_PROXY\"\n")
	b.WriteString("export NO_PROXY=" + ShellQuote(NoProxy) + "\n")
	b.WriteString("exec " + ShellQuote(mainBinary) + " \\\n")
	b.WriteString("  " + ShellQuote("--proxy-server="+u.String()) + " \\\n")
	b.WriteString("  " + ShellQuote("--proxy-bypass-list="+strings.Join(BypassList, ";")) + " \"$@\"\n")
	return b.String()
}

// CreateWrapper builds (or rebuilds) the wrapper app bundle. It refuses to
// touch any path that is not exactly <appDir>/Antigravity Proxy.app.
func CreateWrapper(appDir string, u *url.URL, appPath string) (string, error) {
	mainBinary, err := MainBinaryAt(appPath)
	if err != nil {
		return "", err
	}
	dir := WrapperDir(appDir)
	if filepath.Base(dir) != DefaultAppName+".app" {
		return "", fmt.Errorf("refusing to write unexpected bundle path %q", dir)
	}
	script := WrapperScript(u, mainBinary)
	if wrapperUpToDate(dir, script) {
		return dir, nil
	}
	if err := os.MkdirAll(appDir, 0o755); err != nil {
		return "", fmt.Errorf("create %s: %w", appDir, err)
	}
	if err := os.RemoveAll(dir); err != nil {
		return "", fmt.Errorf("remove old bundle %s: %w", dir, err)
	}
	macOSDir := filepath.Join(dir, "Contents", "MacOS")
	resDir := filepath.Join(dir, "Contents", "Resources")
	for _, d := range []string{macOSDir, resDir} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			return "", fmt.Errorf("create %s: %w", d, err)
		}
	}
	if err := os.WriteFile(filepath.Join(dir, "Contents", "Info.plist"), []byte(infoPlist), 0o644); err != nil {
		return "", err
	}
	if err := os.WriteFile(filepath.Join(dir, "Contents", "PkgInfo"), []byte("APPL????"), 0o644); err != nil {
		return "", err
	}
	exe := filepath.Join(macOSDir, "launch")
	if err := os.WriteFile(exe, []byte(script), 0o755); err != nil {
		return "", err
	}
	if err := os.Chmod(exe, 0o755); err != nil {
		return "", err
	}
	if icon, err := os.ReadFile(filepath.Join(appPath, "Contents", "Resources", "icon.icns")); err == nil {
		_ = os.WriteFile(filepath.Join(resDir, "AppIcon.icns"), icon, 0o644)
	}
	return dir, nil
}

// wrapperUpToDate reports whether the bundle already has our exact launcher.
func wrapperUpToDate(dir, script string) bool {
	exe := filepath.Join(dir, WrapperRel)
	current, err := os.ReadFile(exe)
	if err != nil || string(current) != script {
		return false
	}
	info, err := os.Stat(exe)
	if err != nil || info.Mode().Perm()&0o111 == 0 {
		return false
	}
	_, err = os.Stat(filepath.Join(dir, "Contents", "Info.plist"))
	return err == nil
}

// RemoveWrapper deletes the generated bundle. It reports whether it existed.
func RemoveWrapper(appDir string) (bool, error) {
	dir := WrapperDir(appDir)
	if filepath.Base(dir) != DefaultAppName+".app" {
		return false, fmt.Errorf("refusing to remove unexpected path %q", dir)
	}
	if _, err := os.Stat(dir); err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return false, nil
		}
		return false, err
	}
	if err := os.RemoveAll(dir); err != nil {
		return false, fmt.Errorf("remove %s: %w", dir, err)
	}
	return true, nil
}

func WrapperExists(appDir string) bool {
	info, err := os.Stat(WrapperExe(appDir))
	return err == nil && !info.IsDir()
}

